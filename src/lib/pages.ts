/** "ИП Иванов И. И. (ИНН …, ОГРНИП …)" or the brand when details are not set. */
function seller(s: StoreSettings): string {
  const name = s.legalName.trim() || BRAND_NAME;
  const ids = [
    s.inn.trim() && `ИНН ${s.inn.trim()}`,
    s.ogrn.trim() && `ОГРН ${s.ogrn.trim()}`,
  ].filter(Boolean);
  return ids.length ? `${name} (${ids.join(", ")})` : name;
}

/** "по телефону +7… или по электронной почте …" — only what is filled in. */
function reachUs(s: StoreSettings): string {
  const parts = [
    s.phone.trim() && `по телефону ${s.phone.trim()}`,
    s.email.trim() && `по электронной почте ${s.email.trim()}`,
  ].filter(Boolean);
  return parts.length ? parts.join(" или ") : "через форму на странице «Контакты»";
}

function emailOrForm(s: StoreSettings): string {
  return s.email.trim()
    ? `на адрес ${s.email.trim()}`
    : "через форму на странице «Контакты»";
}

